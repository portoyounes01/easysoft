/**
 * SAF-T (PT) via the unified API: POST /files {type:"AUDIT", range} then stream the
 * zip artifact. The range must cover an already-ended month (spec constraint).
 * Returns the raw ZIP bytes — the artifact is an archive, not bare XML.
 */
export async function fetchFiskalySaftArchive(params: {
    settings: SystemSettings;
    year: number;
    month: number;
}): Promise<{ bytes: Uint8Array; mimeType: string }> {
    assertFiskalyEnabled(params.settings);
    assertOnline();
    const f = params.settings.fiscal.fiskaly;
    const from = `${params.year}-${String(params.month).padStart(2, '0')}-01`;
    const lastDay = new Date(params.year, params.month, 0).getDate();
    const to = `${params.year}-${String(params.month).padStart(2, '0')}-${String(lastDay).padStart(2, '0')}`;
    const response = await invokeFunction({
        action: 'saft',
        environment: f.environment,
        taxpayerId: f.taxpayerId.trim(),
        from,
        to,
    });
    if (response.status === 'processing') {
        throw new Error(i18n.t('checkout.fiskalySaftProcessing'));
    }
    if (!response.zip_base64) {
        throw new Error(i18n.t('checkout.fiskalySaftMissing'));
    }
    const binary = atob(response.zip_base64);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
        bytes[i] = binary.charCodeAt(i);
    }
    return { bytes, mimeType: response.artifact_type || 'application/zip' };
}

export interface FiskalyHealthCheckResult {
    ok: boolean;
    organization: unknown;
    system: unknown;
}

export async function checkFiskalyFiscalHealth(settings: SystemSettings): Promise<FiskalyHealthCheckResult> {
    assertFiskalyEnabled(settings);
    assertOnline();
    const f = settings.fiscal.fiskaly;
    const response = await invokeFunction({
        action: 'health_check',
        environment: f.environment,
        taxpayerId: f.taxpayerId.trim(),
        systemId: f.systemId.trim(),
    });
    return {
        ok: Boolean(response.ok),
        organization: response.organization,
        system: response.system,
    };
}
